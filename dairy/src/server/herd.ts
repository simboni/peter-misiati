/**
 * Write the receipt for a saved record, once.
 *
 * The receipt row reuses the record's own id, so a double-flush from the
 * offline outbox lands on the same primary key and the ORIGINAL reference code
 * is handed back. A receipt whose code changed on a retry would be worse than
 * no receipt at all — it is the thing the farmer writes in the notebook.
 */
export async function writeReceipt(
  session: Session,
  opts: { id: string; prefix: string; kind: string; summary: string; payload?: unknown },
): Promise<string> {
  const existing = await db.query.receipt.findFirst({
    where: and(eq(s.receipt.id, opts.id), eq(s.receipt.farmId, session.farmId)),
  });
  if (existing) return existing.refCode;

  const ref = refCode(opts.prefix);
  await db
    .insert(s.receipt)
    .values({
      id: opts.id,
      farmId: session.farmId,
      refCode: ref,
      kind: opts.kind,
      summary: opts.summary,
      actorId: session.userId,
      at: new Date(),
      payload: (opts.payload ?? null) as never,
    })
    .onConflictDoNothing();
  return ref;
}

