const ExitInput = z.object({
  id: z.string().uuid().optional(),
  animalId: z.string().uuid("Choose an animal."),
  exitDate: isoDate.optional(),
  reason: z.enum(["SOLD", "DIED", "SLAUGHTERED", "CULLED", "STOLEN", "LOST"]),
  cause: z.string().max(200).optional(),
  valueKes: z.coerce.number().min(0).optional(),
  counterpartyId: z.string().uuid().optional(),
  // The Kenyan price drivers — what a buyer actually pays for.
  weightKg: z.coerce.number().positive().max(2000).optional(),
  monthsPregnant: z.coerce.number().min(0).max(10).optional(),
  dailyYieldAtSaleL: z.coerce.number().min(0).max(80).optional(),
  daysInMilkAtSale: z.coerce.number().int().min(0).max(1500).optional(),
});

export interface ExitResult {
  id: string;
  classAtExit: AnimalClass;
  classLabel: string;
  daysInMilkAtSale: number | null;
  valueKes: number | null;
  warnings: string[];
}

export async function recordExit(
  _prev: unknown,
  formData: FormData,
): Promise<ActionResult<ExitResult>> {
  "use server";
  return guard(async () => {
    const session = await requireCapability("ADMIN");

    const parsed = ExitInput.safeParse(formObject(formData));
    if (!parsed.success) {
      return actionError("Check the highlighted fields.", parsed.error.flatten().fieldErrors);
    }
    const v = parsed.data;
    const exitDate = v.exitDate ?? today();

    const animal = await db.query.animal.findFirst({
      where: and(eq(s.animal.id, v.animalId), eq(s.animal.farmId, session.farmId)),
    });
    assertOwned(animal, session, "animal");

    const { events } = await loadHerdSources(session, { animalIds: [v.animalId] });
    const ev = events.get(v.animalId) ?? emptyEvents();

    const already = ev.exits.find((e) => e.id !== v.id);
    if (already) {
      return actionError(
        `${animal!.name ?? animal!.tag} already left the herd on ${already.exitDate} (${already.reason.toLowerCase()}).`,
      );
    }

    const facts = factsFor(animal!, ev, exitDate);
    const cls = deriveClass(facts, exitDate);
    const status = deriveReproStatus(facts, exitDate);
    const dim = v.daysInMilkAtSale ?? dimOf(facts, exitDate);

    const warnings: string[] = [];
    if (status === "PREGNANT" && v.monthsPregnant == null) {
      warnings.push("She is in calf — record how many months, it is most of what she is worth.");
    }
    if (isMilking(cls) && v.dailyYieldAtSaleL == null) {
      warnings.push("Record what she was giving a day — a buyer pays for litres, not for looks.");
    }
    if (v.reason === "DIED" && !v.cause) {
      warnings.push("Record what she died of, even a guess. It is the only way to see a pattern.");
    }

    const id = v.id ?? newId();
    await db
      .insert(s.animalExit)
      .values({
        id,
        farmId: session.farmId,
        animalId: v.animalId,
        exitDate,
        reason: v.reason,
        cause: v.cause ?? null,
        valueKes: v.valueKes != null ? dec(v.valueKes) : null,
        counterpartyId: v.counterpartyId ?? null,
        classAtExit: cls,
        weightKg: v.weightKg != null ? dec(v.weightKg) : null,
        monthsPregnant: v.monthsPregnant != null ? dec(v.monthsPregnant, 1) : null,
        dailyYieldAtSaleL: v.dailyYieldAtSaleL != null ? dec(v.dailyYieldAtSaleL) : null,
        daysInMilkAtSale: dim ?? null,
        recordedBy: session.userId,
      })
      .onConflictDoNothing();

    // She is gone; nothing outstanding on her is anybody's job any more.
    await db
      .update(s.alert)
      .set({ resolvedAt: new Date(), outcome: `ANIMAL_${v.reason}`, resolvedBy: session.userId })
      .where(
        and(
          eq(s.alert.farmId, session.farmId),
          eq(s.alert.animalId, v.animalId),
          isNull(s.alert.resolvedAt),
        ),
      );

    const who = animal!.name ?? animal!.tag;
    const REASON_WORD: Record<typeof v.reason, string> = {
      SOLD: "sold",
      DIED: "died",
      SLAUGHTERED: "slaughtered",
      CULLED: "culled",
      STOLEN: "stolen",
      LOST: "lost",
    };
    const message =
      `${who} ${REASON_WORD[v.reason]} on ${exitDate} as a ${CLASS_LABEL[cls].toLowerCase()}` +
      (v.valueKes != null ? ` for KES ${v.valueKes.toLocaleString("en-KE")}.` : ".");

    const ref = await writeReceipt(session, {
      id,
      prefix: REF_PREFIX.SALE,
      kind: "ANIMAL_EXIT",
      summary: message,
      payload: { animalId: v.animalId, reason: v.reason, classAtExit: cls },
    });

    updateTag(`herd:${session.farmId}`);

    return actionOk(
      {
        id,
        classAtExit: cls,
        classLabel: CLASS_LABEL[cls],
        daysInMilkAtSale: dim ?? null,
        valueKes: v.valueKes ?? null,
        warnings,
      },
      message,
      ref,
    );
  });
}

