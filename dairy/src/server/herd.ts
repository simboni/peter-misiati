export type AnimalRow = typeof s.animal.$inferSelect;
type CalvingRow = typeof s.calving.$inferSelect & {
  outcomes: (typeof s.calvingOutcome.$inferSelect)[];
};
type ServiceRow = typeof s.service.$inferSelect;
type PdRow = typeof s.pregnancyCheck.$inferSelect;
type DryOffRow = typeof s.dryOff.$inferSelect;
type WeightRow = typeof s.weightObservation.$inferSelect;
type ExitRow = typeof s.animalExit.$inferSelect;
type HeatRow = typeof s.heatObservation.$inferSelect;

export interface AnimalEvents {
  /** Ascending by date throughout — callers rely on it. */
  calvings: CalvingRow[];
  services: ServiceRow[];
  pds: PdRow[];
  dryOffs: DryOffRow[];
  weights: WeightRow[];
  heats: HeatRow[];
  exits: ExitRow[];
}

function emptyEvents(): AnimalEvents {
  return { calvings: [], services: [], pds: [], dryOffs: [], weights: [], heats: [], exits: [] };
}

export interface HerdSources {
  animals: AnimalRow[];
  events: Map<string, AnimalEvents>;
}

function bucket(map: Map<string, AnimalEvents>, animalId: string): AnimalEvents {
  let e = map.get(animalId);
  if (!e) {
    e = emptyEvents();
    map.set(animalId, e);
  }
  return e;
}

/**
 * Load the whole farm's animals and their events in a fixed number of queries.
 *
 * A Kenyan smallholder-commercial herd is tens of animals, low hundreds at the
 * top end, so seven scans and an in-memory group-by is both faster and far
 * easier to reason about than seven correlated sub-selects. `farmId` is in
 * every single `where` — that is the tenancy boundary, not a nicety.
 */
export async function loadHerdSources(
  session: Session,
  opts: { animalIds?: string[] } = {},
): Promise<HerdSources> {
  const farmId = session.farmId;
  const ids = opts.animalIds;
  if (ids && ids.length === 0) return { animals: [], events: new Map() };

  const animals = await db
    .select()
    .from(s.animal)
    .where(ids ? and(eq(s.animal.farmId, farmId), inArray(s.animal.id, ids)) : eq(s.animal.farmId, farmId));

  const known = new Set(animals.map((a) => a.id));
  const events = new Map<string, AnimalEvents>();
  for (const a of animals) events.set(a.id, emptyEvents());

  const [calvings, outcomes, services, pds, dryOffs, weights, heats, exits] = await Promise.all([
    db.select().from(s.calving).where(eq(s.calving.farmId, farmId)),
    db.select().from(s.calvingOutcome).where(eq(s.calvingOutcome.farmId, farmId)),
    db.select().from(s.service).where(eq(s.service.farmId, farmId)),
    db.select().from(s.pregnancyCheck).where(eq(s.pregnancyCheck.farmId, farmId)),
    db.select().from(s.dryOff).where(eq(s.dryOff.farmId, farmId)),
    db.select().from(s.weightObservation).where(eq(s.weightObservation.farmId, farmId)),
    db.select().from(s.heatObservation).where(eq(s.heatObservation.farmId, farmId)),
    db.select().from(s.animalExit).where(eq(s.animalExit.farmId, farmId)),
  ]);

  const outcomesByCalving = new Map<string, (typeof s.calvingOutcome.$inferSelect)[]>();
  for (const o of outcomes) {
    const list = outcomesByCalving.get(o.calvingId) ?? [];
    list.push(o);
    outcomesByCalving.set(o.calvingId, list);
  }

  for (const c of calvings) {
    if (!known.has(c.damId)) continue;
    bucket(events, c.damId).calvings.push({ ...c, outcomes: outcomesByCalving.get(c.id) ?? [] });
  }
  for (const r of services) if (known.has(r.animalId)) bucket(events, r.animalId).services.push(r);
  for (const r of pds) if (known.has(r.animalId)) bucket(events, r.animalId).pds.push(r);
  for (const r of dryOffs) if (known.has(r.animalId)) bucket(events, r.animalId).dryOffs.push(r);
  for (const r of weights) if (known.has(r.animalId)) bucket(events, r.animalId).weights.push(r);
  for (const r of heats) if (known.has(r.animalId)) bucket(events, r.animalId).heats.push(r);
  for (const r of exits) if (known.has(r.animalId)) bucket(events, r.animalId).exits.push(r);

  for (const e of events.values()) {
    e.calvings.sort((a, b) => a.calvedOn.localeCompare(b.calvedOn));
    e.services.sort((a, b) => a.servedOn.localeCompare(b.servedOn));
    e.pds.sort((a, b) => a.checkedOn.localeCompare(b.checkedOn));
    e.dryOffs.sort((a, b) => a.driedOn.localeCompare(b.driedOn));
    e.weights.sort((a, b) => a.observedOn.localeCompare(b.observedOn));
    e.heats.sort((a, b) => a.observedAt.getTime() - b.observedAt.getTime());
    e.exits.sort((a, b) => a.exitDate.localeCompare(b.exitDate));
  }

  return { animals, events };
}

/** A calving with every outcome an abortion is a pregnancy loss, not a parity. */
export function isAbortionCalving(c: CalvingRow): boolean {
  return c.outcomes.length > 0 && c.outcomes.every((o) => o.outcome === "ABORTION");
}

/**
 * Assemble the facts `deriveClass` / `deriveReproStatus` need, **as of a date**.
 *
 * Everything after `asOf` is invisible, which is what makes
 * `herdInventoryReconciliation` and `classAtExit` honest rather than
 * retrospectively rewritten by later events.
 */
export function factsFor(animal: AnimalRow, ev: AnimalEvents, asOf: ISODate): AnimalFacts {
  const calvings = ev.calvings.filter((c) => c.calvedOn <= asOf && !isAbortionCalving(c));
  const services = ev.services.filter((r) => r.servedOn <= asOf);
  const pds = ev.pds.filter((r) => r.checkedOn <= asOf);
  const dryOffs = ev.dryOffs.filter((r) => r.driedOn <= asOf);
  const weights = ev.weights.filter((r) => r.observedOn <= asOf && r.weightKg != null);
  const exit = ev.exits.find((r) => r.exitDate <= asOf) ?? null;

  const lastCalvingOn = calvings.length ? calvings[calvings.length - 1].calvedOn : null;
  const lastService = services.length ? services[services.length - 1] : null;
  const positives = pds.filter((p) => p.result === "POSITIVE");
  const negatives = pds.filter((p) => p.result === "NEGATIVE");

  // The expected calving date belongs to the service she is currently carrying.
  // Prefer the service a positive diagnosis actually pointed at.
  let edd: ISODate | null = lastService?.expectedCalvingOn ?? null;
  const lastPositive = positives.length ? positives[positives.length - 1] : null;
  if (lastPositive?.serviceId) {
    const tied = services.find((r) => r.id === lastPositive.serviceId);
    if (tied?.expectedCalvingOn) edd = tied.expectedCalvingOn;
  }
  if (!edd && lastService) {
    edd = breedingCalendar(lastService.servedOn, animal.primaryBreed).expectedCalvingOn;
  }

  return {
    sex: animal.sex,
    dateOfBirth: animal.dateOfBirth,
    castrated: animal.castrated,
    classOverride: animal.classOverride,
    parity: calvings.length,
    lastCalvingOn,
    lastServiceOn: lastService?.servedOn ?? null,
    pdPositiveOn: lastPositive?.checkedOn ?? null,
    pdNegativeOn: negatives.length ? negatives[negatives.length - 1].checkedOn : null,
    driedOffOn: dryOffs.length ? dryOffs[dryOffs.length - 1].driedOn : null,
    expectedCalvingOn: edd,
    latestWeightKg: weights.length ? num(weights[weights.length - 1].weightKg) : null,
    culled: exit?.reason === "CULLED",
  };
}

