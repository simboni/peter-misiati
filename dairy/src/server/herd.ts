export interface InventoryReconciliation {
  from: ISODate;
  to: ISODate;
  opening: number;
  births: number;
  purchases: number;
  otherIn: number;
  deaths: number;
  sales: number;
  otherOut: number;
  closing: number;
  /** opening + births + purchases + otherIn − deaths − sales − otherOut */
  computedClosing: number;
  balances: boolean;
  difference: number;
  byExitReason: Record<string, number>;
  /** Plain language, for a screen a farmer reads rather than an auditor. */
  narrative: string;
}

/**
 * Opening + births + purchases − deaths − sales = closing.
 *
 * This is the number a co-operative, an insurer or a bank asks for, and the one
 * a farm can never produce from a notebook. It is derived entirely from
 * `enteredHerdOn` and `animal_exit`, so it cannot drift from the register.
 */
export async function herdInventoryReconciliation(
  session: Session,
  from: ISODate,
  to: ISODate,
): Promise<InventoryReconciliation> {
  const animals = await db.select().from(s.animal).where(eq(s.animal.farmId, session.farmId));
  const exits = await db
    .select()
    .from(s.animalExit)
    .where(eq(s.animalExit.farmId, session.farmId));

  const exitOf = new Map<string, ExitRow>();
  for (const e of exits) {
    const prev = exitOf.get(e.animalId);
    if (!prev || e.exitDate < prev.exitDate) exitOf.set(e.animalId, e);
  }

  const present = (a: AnimalRow, on: ISODate) => {
    if (a.enteredHerdOn > on) return false;
    const e = exitOf.get(a.id);
    return !e || e.exitDate > on;
  };

  const dayBefore = addDays(from, -1);
  const opening = animals.filter((a) => present(a, dayBefore)).length;
  const closing = animals.filter((a) => present(a, to)).length;

  const arrivals = animals.filter((a) => a.enteredHerdOn >= from && a.enteredHerdOn <= to);
  const births = arrivals.filter((a) => a.origin === "BORN").length;
  const purchases = arrivals.filter((a) => a.origin === "PURCHASED").length;
  const otherIn = arrivals.length - births - purchases;

  const departures = exits.filter((e) => e.exitDate >= from && e.exitDate <= to);
  const byExitReason: Record<string, number> = {};
  for (const e of departures) byExitReason[e.reason] = (byExitReason[e.reason] ?? 0) + 1;

  const deaths = departures.filter((e) => e.reason === "DIED").length;
  const sales = departures.filter((e) => e.reason === "SOLD" || e.reason === "CULLED").length;
  const otherOut = departures.length - deaths - sales;

  const computedClosing = opening + births + purchases + otherIn - deaths - sales - otherOut;
  const difference = closing - computedClosing;

  const narrative =
    `You started with ${opening}. ${births} born, ${purchases} bought` +
    (otherIn ? `, ${otherIn} in another way` : "") +
    `; ${deaths} died, ${sales} sold or culled` +
    (otherOut ? `, ${otherOut} left another way` : "") +
    `. You should have ${computedClosing} — the register says ${closing}.` +
    (difference === 0 ? " It balances." : ` That is ${Math.abs(difference)} out.`);

  return {
    from,
    to,
    opening,
    births,
    purchases,
    otherIn,
    deaths,
    sales,
    otherOut,
    closing,
    computedClosing,
    balances: difference === 0,
    difference,
    byExitReason,
    narrative,
  };
}

