export interface ScheduleItem {
  routine: string;
  label: string;
  dueOn: ISODate;
  /** After this date the window has closed — S19 and disbudding both have one. */
  windowClosesOn: ISODate | null;
  onceInLifetime: boolean;
  /** One person, one animal, one action, one deadline. */
  action: string;
  note?: string;
  severity: "INFO" | "WARN" | "CRITICAL";
  assignedRole: "HERDSMAN" | "MANAGER";
}

const VACCINE_ROUTINES = new Set(["S19", "ECF_ITM", "FMD", "LSD", "ANTHRAX_BQ"]);

function routineAction(rule: RoutineRule, dueOn: ISODate, closesOn: ISODate | null): string {
  const window = closesOn ? ` Do it before ${closesOn}.` : "";
  return `${rule.label} — due ${dueOn}.${window}`;
}

/**
 * One registration in, a year of reminders out.
 *
 * Eligibility is checked *at the date the dose would fall*, which is what keeps
 * S19 off a bull calf's list rather than putting it there and refusing it four
 * months later.
 */
export function firstYearSchedule(
  animal: { sex: "F" | "M"; birthOn: ISODate },
  rules: RoutineRule[] = KENYA_ROUTINES,
): ScheduleItem[] {
  const { sex, birthOn } = animal;
  const items: ScheduleItem[] = [];

  items.push({
    routine: "COLOSTRUM",
    label: "Colostrum",
    dueOn: birthOn,
    windowClosesOn: addDays(birthOn, COLOSTRUM_DAYS),
    onceInLifetime: true,
    action:
      "Give 4 litres of colostrum in the first 6 hours, then keep her on it for 4 days. Do not put this milk in the can.",
    note: "The single biggest thing you can do for a calf, and it cannot be done late.",
    severity: "CRITICAL",
    assignedRole: "HERDSMAN",
  });

  for (const rule of rules) {
    if (rule.firstDoseMinAgeDays == null) continue;
    if (rule.firstDoseMinAgeDays > 365) continue;
    const elig = checkRoutineEligibility(rule, {
      sex,
      ageDays: rule.firstDoseMinAgeDays,
      alreadyGivenCount: 0,
    });
    if (!elig.eligible) continue;

    const dueOn = addDays(birthOn, rule.firstDoseMinAgeDays);
    const closesOn =
      rule.firstDoseMaxAgeDays != null ? addDays(birthOn, rule.firstDoseMaxAgeDays) : null;
    items.push({
      routine: rule.routine,
      label: rule.label,
      dueOn,
      windowClosesOn: closesOn,
      onceInLifetime: rule.onceInLifetime === true,
      action: routineAction(rule, dueOn, closesOn),
      note: rule.note,
      severity: closesOn ? "WARN" : "INFO",
      assignedRole: VACCINE_ROUTINES.has(rule.routine) ? "MANAGER" : "HERDSMAN",
    });
  }

  const weanOn = addDays(birthOn, Math.round(WEANING_AGE_MONTHS * 30.4375));
  items.push({
    routine: "WEANING",
    label: "Weaning target",
    dueOn: weanOn,
    windowClosesOn: null,
    onceInLifetime: true,
    action: `Weaning target ${weanOn} — she should be eating 1.5 kg of calf pellets a day before the milk stops.`,
    severity: "INFO",
    assignedRole: "HERDSMAN",
  });

  items.sort((a, b) => a.dueOn.localeCompare(b.dueOn) || a.routine.localeCompare(b.routine));
  return items;
}

/**
 * Persist the schedule as alerts. Keyed on animal + routine, so a replayed
 * offline registration adds nothing the second time.
 */
async function writeSchedule(
  session: Session,
  animalId: string,
  items: ScheduleItem[],
): Promise<void> {
  if (items.length === 0) return;
  await db
    .insert(s.alert)
    .values(
      items.map((i) => ({
        id: newId(),
        farmId: session.farmId,
        kind: `${ROUTINE_ALERT_PREFIX}${i.routine}`,
        animalId,
        assignedRole: i.assignedRole as s.Role,
        action: i.action,
        dueOn: i.dueOn,
        severity: i.severity,
        dedupeKey: `${animalId}:${ROUTINE_ALERT_PREFIX}${i.routine}`,
      })),
    )
    .onConflictDoNothing();
}

