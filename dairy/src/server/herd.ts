export interface RegisterAnimalResult {
  id: string;
  tag: string;
  name: string | null;
  cls: AnimalClass;
  classLabel: string;
  /** R7 — shown at the moment of entry, not next month. */
  schedule: ScheduleItem[];
}

export async function registerAnimal(
  _prev: unknown,
  formData: FormData,
): Promise<ActionResult<RegisterAnimalResult>> {
  "use server";
  return guard(async () => {
    // 1. Capability. Changing the herd register is an ADMIN act.
    const session = await requireCapability("ADMIN");

    // 2. Shape.
    const parsed = RegisterInput.safeParse(formObject(formData));
    if (!parsed.success) {
      return actionError("Check the highlighted fields.", parsed.error.flatten().fieldErrors);
    }
    const v = parsed.data;
    const enteredHerdOn = v.enteredHerdOn ?? v.dateOfBirth ?? today();

    // 3. Ownership — a well-formed dam UUID can belong to another farm.
    if (v.damId) {
      const dam = await db.query.animal.findFirst({
        where: and(eq(s.animal.id, v.damId), eq(s.animal.farmId, session.farmId)),
      });
      assertOwned(dam, session, "dam");
    }
    if (v.sireId) {
      const sire = await db.query.animal.findFirst({
        where: and(eq(s.animal.id, v.sireId), eq(s.animal.farmId, session.farmId)),
      });
      assertOwned(sire, session, "sire");
    }

    const duplicate = await db.query.animal.findFirst({
      where: and(eq(s.animal.farmId, session.farmId), eq(s.animal.tag, v.tag)),
    });
    if (duplicate && duplicate.id !== v.id) {
      return actionError("That tag is already on another animal.", {
        tag: [`Tag ${v.tag} belongs to ${duplicate.name ?? "another animal"}.`],
      });
    }

    // 4. Write. Client id + onConflictDoNothing = offline-safe.
    const id = v.id ?? newId();
    await db
      .insert(s.animal)
      .values({
        id,
        farmId: session.farmId,
        tag: v.tag,
        name: v.name ?? null,
        sex: v.sex,
        primaryBreed: v.primaryBreed ?? null,
        breedComposition: v.breedComposition ?? null,
        dateOfBirth: v.dateOfBirth ?? null,
        dobEstimated: v.dobEstimated,
        sireId: v.sireId ?? null,
        damId: v.damId ?? null,
        sireStrawCode: v.sireStrawCode ?? null,
        origin: v.origin,
        enteredHerdOn,
        purchasePriceKes: v.purchasePriceKes != null ? dec(v.purchasePriceKes) : null,
        klbaRegNo: v.klbaRegNo ?? null,
        classOverride: v.classOverride ?? null,
        castrated: v.castrated,
        notes: v.notes ?? null,
      })
      .onConflictDoNothing();

    // 5. R7 — the first year of reminders, generated and shown now.
    const born = v.dateOfBirth;
    const youngEnough = born != null && (ageDays(born, enteredHerdOn) ?? 9999) <= 365;
    const schedule = youngEnough ? firstYearSchedule({ sex: v.sex, birthOn: born! }) : [];
    if (schedule.length) await writeSchedule(session, id, schedule);

    const facts: AnimalFacts = {
      sex: v.sex,
      dateOfBirth: v.dateOfBirth ?? null,
      castrated: v.castrated,
      classOverride: v.classOverride ?? null,
      parity: 0,
      lastCalvingOn: null,
      lastServiceOn: null,
      pdPositiveOn: null,
      pdNegativeOn: null,
      driedOffOn: null,
      expectedCalvingOn: null,
      latestWeightKg: null,
      culled: false,
    };
    const cls = deriveClass(facts, today());

    // 6. Receipt (R6).
    const who = v.name ? `${v.name} (${v.tag})` : v.tag;
    const ref = await writeReceipt(session, {
      id,
      prefix: HERD_REF.ANIMAL,
      kind: "ANIMAL_REGISTERED",
      summary:
        schedule.length > 0
          ? `${who} added to the herd. ${schedule.length} reminders set for her first year.`
          : `${who} added to the herd.`,
      payload: { animalId: id, schedule },
    });

    updateTag(`herd:${session.farmId}`);

    return actionOk(
      { id, tag: v.tag, name: v.name ?? null, cls, classLabel: CLASS_LABEL[cls], schedule },
      schedule.length > 0
        ? `${who} is registered. Here is her first year.`
        : born
          ? `${who} is registered.`
          : `${who} is registered. Add her date of birth to get her vaccination dates.`,
      ref,
    );
  });
}

