export interface WeightResult {
  id: string;
  weightKg: number | null;
  bcs: number | null;
  /** R7 — the number that means something: growth since last time. */
  gainGramsPerDay: number | null;
  sinceDays: number | null;
  warnings: string[];
}

export async function recordWeight(
  _prev: unknown,
  formData: FormData,
): Promise<ActionResult<WeightResult>> {
  "use server";
  return guard(async () => {
    const session = await requireCapability("RECORD");

    const parsed = WeightInput.safeParse(formObject(formData));
    if (!parsed.success) {
      return actionError("Check the highlighted fields.", parsed.error.flatten().fieldErrors);
    }
    const v = parsed.data;
    const observedOn = v.observedOn ?? today();

    const animal = await db.query.animal.findFirst({
      where: and(eq(s.animal.id, v.animalId), eq(s.animal.farmId, session.farmId)),
    });
    assertOwned(animal, session, "animal");

    const warnings: string[] = [];

    // BCS is a five-point scale in quarter steps. Snapping is a correction, not
    // a rejection — R4 means we never throw the entry away.
    let bcs: number | null = null;
    if (v.bcs != null) {
      bcs = Math.round(v.bcs * 4) / 4;
      if (bcs !== v.bcs) {
        warnings.push(`Body condition is scored in quarter steps — saved as ${bcs.toFixed(2)}.`);
      }
    }

    // R4 again: an implausible weight is flagged, never refused.
    if (v.weightKg != null) {
      const months = ageMonths(animal!.dateOfBirth, observedOn);
      if (v.weightKg > 900) warnings.push("That is very heavy for a dairy cow — check the reading.");
      if (v.weightKg < 20) warnings.push("That is very light — check the reading.");
      if (months != null && months < 6 && v.weightKg > 250) {
        warnings.push("That is heavy for a calf under six months — check the reading.");
      }
    }

    const previous = await db
      .select()
      .from(s.weightObservation)
      .where(
        and(
          eq(s.weightObservation.farmId, session.farmId),
          eq(s.weightObservation.animalId, v.animalId),
        ),
      );
    const priorWeights = previous
      .filter((r) => r.weightKg != null && r.observedOn < observedOn)
      .sort((a, b) => a.observedOn.localeCompare(b.observedOn));
    const last = priorWeights.length ? priorWeights[priorWeights.length - 1] : null;

    let gain: number | null = null;
    let sinceDays: number | null = null;
    if (last && v.weightKg != null) {
      sinceDays = daysBetween(last.observedOn, observedOn);
      if (sinceDays > 0) {
        gain = Math.round(((v.weightKg - num(last.weightKg)) * 1000) / sinceDays);
      }
    }

    const id = v.id ?? newId();
    await db
      .insert(s.weightObservation)
      .values({
        id,
        farmId: session.farmId,
        animalId: v.animalId,
        observedOn,
        weightKg: v.weightKg != null ? dec(v.weightKg) : null,
        method: v.method ?? null,
        bcs: bcs != null ? dec(bcs) : null,
        recordedBy: session.userId,
      })
      .onConflictDoNothing();

    const who = animal!.name ?? animal!.tag;
    const parts: string[] = [];
    if (v.weightKg != null) parts.push(`${v.weightKg} kg`);
    if (bcs != null) parts.push(`body condition ${bcs.toFixed(2)}`);
    let message = `${who}: ${parts.join(", ")} recorded.`;
    if (gain != null) {
      message +=
        gain >= 0
          ? ` She has gained ${gain} g a day since ${last!.observedOn}.`
          : ` She has LOST ${Math.abs(gain)} g a day since ${last!.observedOn}.`;
    }

    const ref = await writeReceipt(session, {
      id,
      prefix: HERD_REF.WEIGHT,
      kind: "WEIGHT",
      summary: message,
      payload: { animalId: v.animalId, weightKg: v.weightKg ?? null, bcs },
    });

    updateTag(`herd:${session.farmId}`);

    return actionOk(
      { id, weightKg: v.weightKg ?? null, bcs, gainGramsPerDay: gain, sinceDays, warnings },
      message,
      ref,
    );
  });
}

