export interface HerdRow {
  id: string;
  tag: string;
  name: string | null;
  sex: "F" | "M";
  primaryBreed: string | null;
  breedComposition: string | null;
  dateOfBirth: ISODate | null;
  dobEstimated: boolean;
  ageMonths: number | null;
  /** Derived, always. There is no class column and there never will be. */
  cls: AnimalClass;
  classLabel: string;
  classIsOverridden: boolean;
  reproStatus: ReproStatus;
  daysInMilk: number | null;
  parity: number;
  lastCalvingOn: ISODate | null;
  lastServiceOn: ISODate | null;
  expectedCalvingOn: ISODate | null;
  latestWeightKg: number | null;
  latestBcs: number | null;
  latestWeightOn: ISODate | null;
  milking: boolean;
  exited: boolean;
  exitDate: ISODate | null;
  exitReason: string | null;
}

export interface ListHerdOptions {
  asOf?: ISODate;
  /** Filter on the DERIVED class, after derivation. */
  cls?: AnimalClass | null;
  /** Matches name or tag, case-insensitive, anywhere in the string. */
  search?: string | null;
  includeExited?: boolean;
  sex?: "F" | "M" | null;
}

export interface HerdList {
  asOf: ISODate;
  rows: HerdRow[];
  /** Counts across the whole herd, not just the filtered page. */
  countsByClass: Record<string, number>;
  total: number;
  milkingCount: number;
}

export async function listHerd(session: Session, opts: ListHerdOptions = {}): Promise<HerdList> {
  const asOf = opts.asOf ?? today();
  const { animals, events } = await loadHerdSources(session);

  const all: HerdRow[] = animals.map((a) => {
    const ev = events.get(a.id) ?? emptyEvents();
    const facts = factsFor(a, ev, asOf);
    const cls = deriveClass(facts, asOf);
    const status = deriveReproStatus(facts, asOf);
    const weights = ev.weights.filter((w) => w.observedOn <= asOf);
    const lastWeight = [...weights].reverse().find((w) => w.weightKg != null) ?? null;
    const lastBcs = [...weights].reverse().find((w) => w.bcs != null) ?? null;
    const exit = ev.exits.find((e) => e.exitDate <= asOf) ?? null;

    return {
      id: a.id,
      tag: a.tag,
      name: a.name,
      sex: a.sex,
      primaryBreed: a.primaryBreed,
      breedComposition: a.breedComposition,
      dateOfBirth: a.dateOfBirth,
      dobEstimated: a.dobEstimated,
      ageMonths: a.dateOfBirth ? Math.floor(ageMonths(a.dateOfBirth, asOf)!) : null,
      cls,
      classLabel: CLASS_LABEL[cls],
      classIsOverridden: a.classOverride != null,
      reproStatus: status,
      daysInMilk: dimOf(facts, asOf),
      parity: facts.parity,
      lastCalvingOn: facts.lastCalvingOn,
      lastServiceOn: facts.lastServiceOn,
      expectedCalvingOn: status === "PREGNANT" ? facts.expectedCalvingOn : null,
      latestWeightKg: lastWeight ? num(lastWeight.weightKg) : null,
      latestBcs: lastBcs ? num(lastBcs.bcs) : null,
      latestWeightOn: lastWeight?.observedOn ?? null,
      milking: isMilking(cls) && status !== "DRY",
      exited: exit != null,
      exitDate: exit?.exitDate ?? null,
      exitReason: exit?.reason ?? null,
    };
  });

  const inHerd = all.filter((r) => opts.includeExited || !r.exited);

  const countsByClass: Record<string, number> = {};
  for (const r of inHerd) countsByClass[r.cls] = (countsByClass[r.cls] ?? 0) + 1;

  const needle = opts.search?.trim().toLowerCase() ?? "";
  const rows = inHerd
    .filter((r) => (opts.cls ? r.cls === opts.cls : true))
    .filter((r) => (opts.sex ? r.sex === opts.sex : true))
    .filter((r) =>
      needle === ""
        ? true
        : r.tag.toLowerCase().includes(needle) || (r.name ?? "").toLowerCase().includes(needle),
    )
    .sort(
      (a, b) =>
        a.cls.localeCompare(b.cls) ||
        (a.name ?? a.tag).localeCompare(b.name ?? b.tag) ||
        a.tag.localeCompare(b.tag),
    );

  return {
    asOf,
    rows,
    countsByClass,
    total: inHerd.length,
    milkingCount: inHerd.filter((r) => r.milking).length,
  };
}

